    /// The manifold dimension of `id` and its inverse-retraction, as an erased operation.
    ///
    /// Both halves are needed together to build `x ⊖ p` from an id: the operation to register, and
    /// the dimension, which is the width of the resulting tangent -- and which is the *manifold*
    /// dimension, not the storage size, so an `SE3` quantity reports 6 rather than 12.
    ///
    /// Errors [`SkoroError::NotContinuous`] for a discrete quantity, which has no tangent space,
    /// and [`SkoroError::NodeNotFound`] for an unknown id.
    pub fn inverse_retraction_op(
        &self,
        id: Id,
    ) -> SkoroResult<(usize, Box<dyn DynGraphOperation<B>>)> {
        let quantity_type = self.get_quantity_type_impl(id)?;
        let op = quantity_type
            .inverse_retraction_op()
            .ok_or(SkoroError::NotContinuous { id })?;
        let dimension = quantity_type
            .as_manifold()
            .ok_or(SkoroError::NotContinuous { id })?
            .dimension();
        Ok((dimension, op))
    }

    /// The stacked tangent `δ = [x1 ⊖ p1 ; … ; xk ⊖ pk]` over a heterogeneous set of
    /// quantities, as one `EuclideanD(Σ di)` node.
    ///
    /// This is what lets a single factor score a runtime collection of *several* quantities at
    /// once. A joint likelihood over a Markov blanket needs exactly that, and no distribution can
    /// express it -- a distribution is designed to have a [`Sampler`], which is over one quantity
    /// type. This is deliberately **not** a product manifold: the members keep their own ids,
    /// their own storage, and their own children, and only their *tangents* are stacked. A
    /// product would have to re-home them into one merged quantity, which is exactly what
    /// [`demote_to_parameter`](Self::demote_to_parameter) exists to avoid.
    ///
    /// Each `pi` is frozen as a batch-pinned [`Constant`](crate::node::ConstantNode) of
    /// `xi`'s own quantity type. That is the point of the call rather than an implementation
    /// detail: a factor linearized at an estimate must not follow the quantity it summarizes,
    /// so the anchor is a snapshot and never a live node. Because the anchors are batch-pinned,
    /// a batch of `N` independent problems carries `N` independent linearization points --
    /// and the graph is thereafter pinned to that batch.
    ///
    /// The anchor points `pi` and residual tangents `xi ⊖ pi` are never handed to the caller, who
    /// holds only the `xi` and the output `δ`. They are recorded as private nodes
    /// ([`is_private`](Self::is_private)): [`remove_closure`](Self::remove_closure) reclaims one
    /// as soon as nothing points at it, and a model's mark-and-sweep collects them with `δ`,
    /// since they are its ancestors and not roots.
    pub fn stacked_tangent(&mut self, at: &PointMap<B>, ids: &[Id]) -> SkoroResult<Id> {
        if ids.is_empty() {
            return Err(SkoroError::ShapeMismatch {
                expected: 1,
                found: 0,
            });
        }
        let mut widths = Vec::with_capacity(ids.len());
        let mut blocks = Vec::with_capacity(ids.len());
        for &id in ids {
            let (dimension, op) = self.inverse_retraction_op(id)?;
            let quantity_type = self.get_quantity_type_impl(id)?.clone_arc();
            let (value, _) = at.get(&id).ok_or(SkoroError::MissingPoint { id })?;
            let anchor = self.add_batched_constant_dyn(quantity_type, value.clone())?;
            // `inverse_retract(point, other)` yields `other ⊖ point`, so the anchor goes first:
            // the residual is the displacement *from* the linearization point.
            let block =
                self.add_mapped_dyn(EuclideanD(dimension).into_dyn(), op, vec![anchor, id])?;
            // Neither is ever handed out, so both are the graph's to reclaim. The
            // concatenation below is the caller's and stays out of the set.
            self.private_nodes.insert(anchor);
            self.private_nodes.insert(block);
            widths.push(dimension);
            blocks.push(block);
        }
        let total = widths.iter().sum();
        self.add_mapped_dyn(
            EuclideanD(total).into_dyn(),
            Box::new(DiffGraphOperation(TangentConcat(widths))),
            blocks,
        )
    }

    fn add_mapped_impl(
        &mut self,
        quantity_type: Arc<dyn DynQuantityType<B>>,
        op: Arc<dyn DynGraphOperation<B>>,
        parent_ids: Vec<Id>,
    ) -> SkoroResult<Id> {
        let id = self.id_generator.issue_id();
        self.register_children(id, &parent_ids)?;
        let value = self.check_cache(&parent_ids, &op)?;
        self.nodes.insert(
            id,
            Node::Mapped(MappedNode {
                id,
                op,
                parent_ids,
                quantity_type,
                value,
            }),
        );
        self.touch();
        Ok(id)
    }

    /// Mark a mapped quantity as a log-density for the stochastic quantity.
    ///
    /// A _log-density_ is a log-likelihood factor associated with a marginal distribution of
    /// a stochastic quantity. The two types of quantities are in one-to-one correspondence.
    /// Every stochastic quantity has a log-density, and every log-density is associated with a
    /// single stochastic quantity.
    ///
    /// The same cannot be said about log-likelihoods, which may simply be importance-sampling
    /// factors that may depend on more than one quantity at a time and do not describe the
    /// likelihoods of any specific marginal distribution.
    ///
    /// One-to-one is about *pairing*, not about scoring: it says every stochastic quantity has
    /// exactly one density node, not that every such density is a summand of the model's
    /// log-density. [`mark_log_proposal`](Self::mark_log_proposal) makes the same pairing for a
    /// term that belongs to the generative model alone.
    pub fn mark_log_density(&mut self, id: Id, stochastic_id: Id) -> SkoroResult<()> {
        self.mark_log_density_impl(id, stochastic_id, true)
    }

    /// Mark a mapped quantity as the *proposal-only* density for the stochastic quantity.
    ///
    /// Identical to [`mark_log_density`](Self::mark_log_density) — same one-to-one pairing, same
    /// guards, same errors — except that the term is not a summand of the model's log-density.
    /// It scores the quantity under the generative mechanism `q(x|z)` only, so
    /// [`log_density`](Self::log_density) skips it while
    /// [`terms`](Self::terms) still reports it with `in_proposal` set.
    ///
    /// Promoting an existing free-standing likelihood factor this way moves it *out* of the
    /// log-density: the factor keeps its identity and its place in term order, but stops being
    /// a summand of `p`.
    pub fn mark_log_proposal(&mut self, id: Id, stochastic_id: Id) -> SkoroResult<()> {
        self.mark_log_density_impl(id, stochastic_id, false)
    }

    fn mark_log_density_impl(
        &mut self,
        id: Id,
        stochastic_id: Id,
        in_log_density: bool,
    ) -> SkoroResult<()> {
        // If it already is the log-density for the stochastic quantity, this is a no-op; if it
        // already is the log-density of another stochastic quantity, we would break the one-to-one
        // correspondence invariant.
        if let Some(existing) = self.stochastic_to_log_density.get(&stochastic_id) {
            if *existing == id {
                return Ok(());
            } else {
                return Err(SkoroError::DuplicateDensity { stochastic_id });
            }
        }

        // Remove the node so that we may reinsert it as a new node type (be sure to add node back
        // in when errors are raised so graph doesn't break).
        let out = match self.nodes.remove(&id) {
            // Error if quantity not found.
            None => Err(SkoroError::NodeNotFound { id }),
            // Promote a bare likelihood factor to the density of `stochastic_id`.
            Some(Node::LogLikelihood(mut node)) => {
                // Rebinding a density to a second quantity would strand the first's
                // `stochastic_to_log_density` entry. The guard is unconditional: in release the
                // silent rebind is exactly the corruption `validate_indices` exists to catch,
                // and there is no debug assertion left to catch it.
                if node.stochastic_id.is_some() {
                    self.nodes.insert(id, Node::LogLikelihood(node));
                    return Err(SkoroError::DuplicateDensity { stochastic_id });
                }
                node.stochastic_id = Some(stochastic_id);
                node.in_log_density = in_log_density;
                self.stochastic_to_log_density.insert(stochastic_id, id);
                // No `log_likelihoods.push` here: the node was already a likelihood term, so it
                // is already named in the arena. Promoting it to a density does not add a factor,
                // it only gives the existing one a stochastic quantity to score.
                self.nodes.insert(id, Node::LogLikelihood(node));
                Ok(())
            }
            // Mapped values must be real.
            Some(Node::Mapped(node)) => {
                if !node.quantity_type.compare(&Real) {
                    // reinsert before error
                    self.nodes.insert(id, Node::Mapped(node));
                    Err(SkoroError::NotReal { id })
                } else {
                    self.stochastic_to_log_density.insert(stochastic_id, id);
                    self.log_likelihoods.push(id);
                    self.nodes.insert(
                        id,
                        Node::LogLikelihood(LogLikelihoodNode {
                            id: node.id,
                            op: node.op,
                            parent_ids: node.parent_ids,
                            quantity_type: node.quantity_type,
                            value: node.value,
                            stochastic_id: Some(stochastic_id),
                            in_log_density,
                        }),
                    );
                    Ok(())
                }
            }
            // Must be a mapped value.
            Some(node) => {
                // reinsert before error
                self.nodes.insert(id, node);
                Err(SkoroError::NotMapped { id })
            }
        };
        self.touch();
        out
    }

    /// Mark a mapped quantity as a likelihood.
    ///
    /// Callers may specify that any transformed real quantity in the model is a log-likelihood term.
    pub fn mark_log_likelihood(&mut self, id: Id) -> SkoroResult<()> {
        // Remove the node so that we may reinsert it as a new node type (be sure to add node back
        // in when errors are raised so graph doesn't break).
        let out = match self.nodes.remove(&id) {
            // Error if quantity not found.
            None => Err(SkoroError::NodeNotFound { id }),
            // No-op if already a log-likelihood; error if a log-density.
            Some(Node::LogLikelihood(node)) => {
                // branch on if log-density
                if node.stochastic_id.is_some() {
                    self.nodes.insert(id, Node::LogLikelihood(node));
                    Err(SkoroError::MustRemainDensity { id })
                } else {
                    self.nodes.insert(id, Node::LogLikelihood(node));
                    Ok(())
                }
            }
            // Mapped values must be real.
            Some(Node::Mapped(node)) => {
                if !node.quantity_type.compare(&Real) {
                    // reinsert before error
                    self.nodes.insert(id, Node::Mapped(node));
                    Err(SkoroError::NotReal { id })
                } else {
                    self.log_likelihoods.push(id);
                    self.nodes.insert(
                        id,
                        Node::LogLikelihood(LogLikelihoodNode {
                            id: node.id,
                            op: node.op,
                            parent_ids: node.parent_ids,
                            value: node.value,
                            quantity_type: node.quantity_type,
                            stochastic_id: None,
                            in_log_density: true,
                        }),
                    );
                    Ok(())
                }
            }
            Some(node) => {
                // re-insert the node we removed before erroring
                self.nodes.insert(id, node);
                Err(SkoroError::NotMapped { id })
            }
        };
        self.touch();
        out
    }

    /// Retire a term, turning it back into an ordinary [`Node::Mapped`].
    ///
    /// Term membership goes with the node type: a mapped node is a summand of nothing, so
    /// [`in_log_density`](crate::node::LogLikelihoodNode::in_log_density) is dropped rather than
    /// remembered. Re-marking the node with
    /// [`mark_log_likelihood`](Self::mark_log_likelihood) therefore brings it back as a summand
    /// of the log-density, even if it had been proposal-only. That is consistent with this
    /// method retiring a factor rather than suspending it; use
    /// [`mark_log_proposal`](Self::mark_log_proposal) to restore a proposal-only term.
    pub fn unmark_log_likelihood(&mut self, id: Id) -> SkoroResult<()> {
        let out = match self.nodes.remove(&id) {
            None => Err(SkoroError::NodeNotFound { id }),
            Some(Node::LogLikelihood(node)) => {
                if let Some(stochastic_id) = node.stochastic_id {
                    self.stochastic_to_log_density.remove(&stochastic_id);
                }
                if let Some(index) = self.log_likelihoods.iter().position(|lid| *lid == id) {
                    self.log_likelihoods.remove(index);
                }
                self.nodes.insert(
                    id,
                    Node::Mapped(MappedNode {
                        id,
                        op: node.op,
                        parent_ids: node.parent_ids,
                        quantity_type: node.quantity_type,
                        value: node.value,
                    }),
                );
                Ok(())
            }
            Some(node) => {
                self.nodes.insert(id, node);
                Err(SkoroError::NotLogLikelihood { id })
            }
        };
        self.touch();
        out
    }

    // Render a quantity in our probabilistic model fixed.
    //
    // This operation will map the `Parameter` and `Stochastic` variants of quantities to `Constant`
    // and `Observed`, respectively. For parameters, observing simply flags that the quantity is no
    // longer free and instead takes a fixed value. Meanwhile, stochastic quantities are deemed
    // "observed", changing the model to a posterior distribution over this quantity (in addition to
    // the other observed nodes).
    pub fn observe<K, T, D>(&mut self, id: Id, value: &D) -> SkoroResult<()>
    where
        K: Kind<B>,
        T: QuantityType<B, K> + Packable<K::Elem, D>,
        D: 'static,
    {
        let quantity_type = self.get_quantity_type::<K, T>(id)?;
        self.observe_impl(
            id,
            QuantityValue::Unbatched(K::wrap_unbatched_point(quantity_type.pack_value(value))),
        )
    }

    // Render a quantity in our probabilistic model fixed.
    //
    // This operation will map the `Parameter` and `Stochastic` variants of quantities to `Constant`
    // and `Observed`, respectively. For parameters, observing simply flags that the quantity is no
    // longer free and instead takes a fixed value. Meanwhile, stochastic quantities are deemed
    // "observed", changing the model to a posterior distribution over this quantity (in addition to
    // the other observed nodes).
    //
    /// One value per batch row, in order, rather than one value broadcast to every row. A batch
    /// is a set of independent problems (independent optimizations, independent conditioning),
    /// and this is how each row gets its own constant.
    ///
    /// The cost is that the value pins the batch: a graph containing a batch-`n` constant can
    /// only be evaluated at batch `n`, and any other batch size is a
    /// [`SkoroError::BatchSizeMismatch`] rather than a broadcast. Use
    /// [`add_constant`](Self::add_constant) for a value shared by every row.
    pub fn observe_batched<K, T, D>(&mut self, id: Id, values: &[D]) -> SkoroResult<()>
    where
        K: Kind<B>,
        T: QuantityType<B, K> + Packable<K::Elem, D>,
        D: 'static,
    {
        let quantity_type = self.get_quantity_type::<K, T>(id)?;
        self.observe_impl(
            id,
            QuantityValue::Batched(K::wrap_point(quantity_type.pack_values(values))),
        )
    }

    // Render a quantity in our probabilistic model fixed.
    //
    // This operation will map the `Parameter` and `Stochastic` variants of quantities to `Constant`
    // and `Observed`, respectively. For parameters, observing simply flags that the quantity is no
    // longer free and instead takes a fixed value. Meanwhile, stochastic quantities are deemed
    // "observed", changing the model to a posterior distribution over this quantity (in addition to
    // the other observed nodes).
    //
    // When called on other types of nodes, this method will return an error.
    fn observe_impl(&mut self, id: Id, value: QuantityValue<B>) -> SkoroResult<()> {
        // the number of components and the quantity kind must be the same
        let is_discrete = value.is_discrete();
        let num_components = value.num_components();
        match self.nodes.get(&id) {
            Some(&Node::Observed(ObservedNode {
                ref quantity_type, ..
            }))
            | Some(&Node::Constant(ConstantNode {
                ref quantity_type, ..
            }))
            | Some(&Node::Stochastic(StochasticNode {
                ref quantity_type, ..
            }))
            | Some(&Node::Parameter(ParameterNode {
                ref quantity_type, ..
            })) => {
                let expected_num_components = quantity_type.num_components();
                if expected_num_components != num_components {
                    return Err(SkoroError::ShapeMismatch {
                        expected: expected_num_components,
                        found: num_components,
                    });
                }
                let expected_is_discrete = quantity_type.kind() == QuantityKind::Discrete;
                if expected_is_discrete != is_discrete {
                    return Err(SkoroError::QuantityTypeMismatch { id });
                }
            }
            Some(_) => return Err(SkoroError::NotObservable { id }),
            None => return Err(SkoroError::NodeNotFound { id }),
        };

        // ensure this observation does not pin the batch to a different number
        let batch = value.pinned_batch();
        if let Some(batch) = batch {
            for pinnable_id in &self.pinnable {
                match self.nodes.get(pinnable_id) {
                    Some(&Node::Constant(ConstantNode { ref value, .. }))
                    | Some(&Node::Observed(ObservedNode { ref value, .. })) => {
                        if *pinnable_id != id
                            && let Some(other_batch) = value.pinned_batch()
                        {
                            if batch != other_batch {
                                return Err(SkoroError::BatchSizeMismatch {
                                    expected: other_batch,
                                    found: batch,
                                });
                            } else {
                                break;
                            }
                        }
                    }
                    _ => {}
                }
            }
        }

        // change the node to its observed counterpart
        match self.nodes.remove(&id) {
            Some(Node::Observed(mut node)) => {
                node.value = value.clone();
                self.nodes.insert(id, Node::Observed(node));
            }
            Some(Node::Constant(mut node)) => {
                node.value = value.clone();
                self.nodes.insert(id, Node::Constant(node));
            }
            Some(Node::Stochastic(StochasticNode {
                id,
                sampler,
                parent_ids,
                quantity_type,
            })) => {
                self.pinnable.insert(id);
                self.nodes.insert(
                    id,
                    Node::Observed(ObservedNode {
                        id,
                        value: value.clone(),
                        sampler,
                        parent_ids,
                        quantity_type,
                    }),
                );
            }
            Some(Node::Parameter(ParameterNode { id, quantity_type })) => {
                self.pinnable.insert(id);
                self.nodes.insert(
                    id,
                    Node::Constant(ConstantNode {
                        id,
                        value: value.clone(),
                        quantity_type,
                    }),
                );
            }
            _ => unreachable!(),
        };

        // Two walks over the same dependency order, and they cannot be merged. The first gathers
        // the values of every *cousin* -- a parent of a descendant that is not itself downstream
        // of `id` -- because folding a node needs all of its parents at once, and a cousin can be
        // any node in the graph, including one that sorts after the descendant that reads it. The
        // second walk then folds, relying on `ancestor_values` being complete before it starts.
        let descendants = self.descendants_in_dependency_order(id);
        let mut ancestor_values = HashMap::new();
        ancestor_values.insert(id, value);
        for id in &descendants {
            match self.nodes.get(id) {
                Some(&Node::Mapped(MappedNode { ref parent_ids, .. }))
                | Some(&Node::LogLikelihood(LogLikelihoodNode { ref parent_ids, .. })) => {
                    for cousin in parent_ids {
                        if let Entry::Vacant(entry) = ancestor_values.entry(*cousin) {
                            match self.nodes.get(cousin) {
                                Some(&Node::Mapped(MappedNode { ref value, .. }))
                                | Some(&Node::LogLikelihood(LogLikelihoodNode {
                                    ref value, ..
                                })) => {
                                    if let Some(value) = value {
                                        entry.insert(value.clone());
                                    }
                                }
                                Some(&Node::Constant(ConstantNode { ref value, .. }))
                                | Some(&Node::Observed(ObservedNode { ref value, .. })) => {
                                    entry.insert(value.clone());
                                }
                                _ => {}
                            }
                        }
                    }
                }
                _ => {}
            }
        }

        // Fold every descendant that has become concrete, each exactly once, in an order
        // where a node is reached only after every parent of it has settled.
        for descendant in &descendants {
            match self.nodes.get_mut(descendant) {
                Some(&mut Node::Mapped(MappedNode {
                    ref mut value,
                    ref parent_ids,
                    ref op,
                    ..
                }))
                | Some(&mut Node::LogLikelihood(LogLikelihoodNode {
                    ref mut value,
                    ref parent_ids,
                    ref op,
                    ..
                })) => {
                    let mut batch = batch;
                    let num_parents = parent_ids.len();
                    let mut points = Vec::with_capacity(num_parents);
                    let mut cacheable = true;
                    for parent_id in parent_ids {
                        if let Some(value) = ancestor_values.get(parent_id) {
                            batch = batch.or(value.pinned_batch());
                            points.push(value.clone());
                        } else {
                            cacheable = false;
                            break;
                        }
                    }
                    if !cacheable {
                        continue;
                    }
                    let batchdim = batch.unwrap_or(1);
                    let mut all_points = Vec::with_capacity(num_parents + 1);
                    points
                        .into_iter()
                        .for_each(|v| {
                            all_points.push(Some(
                                v.materialize(batchdim)
                                    .expect("Cousins should have already been checked to not have a contradicting pinned batch."),
                            ));
                        });
                    all_points.push(None);
                    op.lower(
                        Vec::from_iter(0..num_parents),
                        vec![false; num_parents],
                        num_parents,
                    )
                    .forward(&mut all_points);
                    let cache = all_points[num_parents]
                        .take()
                        .expect("Sequenced operation filled the output point.");
                    let v = if batch.is_some() {
                        QuantityValue::Batched(cache)
                    } else {
                        QuantityValue::Unbatched(cache.unbatch())
                    };
                    ancestor_values.insert(*descendant, v.clone());
                    *value = Some(v);
                }
                _ => {}
            };
        }
        self.touch();
        Ok(())
    }

    /// Every descendant of `id`, ordered so that each follows all of its parents.
    ///
    /// Reachability first, then [`topological_sort`](Self::topological_sort) over that set —
    /// which orders *ancestors* first, so filtering its output back down to the reachable set
    /// gives exactly the dependency order the fold walk needs.
    fn descendants_in_dependency_order(&self, id: Id) -> Vec<Id> {
        let Some(children) = self.children.get(&id) else {
            return Vec::new();
        };
        let mut reachable = HashSet::new();
        let mut queue: VecDeque<Id> = children.iter().copied().collect();
        while let Some(next) = queue.pop_front() {
            if !reachable.insert(next) {
                continue;
            }
            if let Some(children) = self.children.get(&next) {
                queue.extend(children.iter().copied());
            }
        }
        let targets: Vec<Id> = reachable.iter().copied().collect();
        self.topological_sort(&targets)
            .into_iter()
            .filter(|id| reachable.contains(id))
            .collect()
    }

    /// Undo the effects of [`observe`](Self::observe).
    ///
    /// Returns an error if the node does not exist or is not observable.
    pub fn unobserve(&mut self, id: Id) -> SkoroResult<()> {
        // update the node constant => parameter, observed => stochastic.
        //
        // a flag if the node was previously pinned, because this means we may be able to release
        // the pin
        match self.nodes.remove(&id) {
            None => return Err(SkoroError::NodeNotFound { id }),
            Some(Node::Observed(node)) => {
                self.nodes.insert(
                    id,
                    Node::Stochastic(StochasticNode {
                        id,
                        sampler: node.sampler,
                        parent_ids: node.parent_ids,
                        quantity_type: node.quantity_type,
                    }),
                );
            }
            Some(Node::Constant(node)) => {
                self.nodes.insert(
                    id,
                    Node::Parameter(ParameterNode {
                        id,
                        quantity_type: node.quantity_type,
                    }),
                );
            }
            Some(node) => {
                self.nodes.insert(id, node);
                return Err(SkoroError::NotObservable { id });
            }
        };
        self.pinnable.remove(&id);
        self.clear_cached_descendants(id);
        self.touch();
        Ok(())
    }

    /// Drop the constant-folded values cached on every descendant of `id`.
    ///
    /// [`add_mapped`](Self::add_mapped) folds a subtree into
    /// [`MappedNode::value`](crate::node::MappedNode::value) when all of its parents
    /// are already concrete, and `is_differentiable_parent` treats such a node as
    /// non-differentiable. Any mutation that makes a node's value non-constant —
    /// [`unobserve`](Self::unobserve), [`demote_to_parameter`](Self::demote_to_parameter) —
    /// must therefore invalidate those folds, or the descendants are silently dropped
    /// from the tape and the derivatives come back wrong while the values stay right.
    fn clear_cached_descendants(&mut self, id: Id) {
        let Some(children) = self.children.get(&id) else {
            return;
        };
        let mut visit: VecDeque<Id> = children.iter().copied().collect();
        let mut visited = HashSet::new();
        while let Some(cid) = visit.pop_front() {
            visited.insert(cid);
            match self.nodes.get_mut(&cid) {
                Some(Node::Mapped(MappedNode { value, .. }))
                | Some(Node::LogLikelihood(LogLikelihoodNode { value, .. }))
                    if value.is_some() =>
                {
                    value.take();
                    if let Some(children) = self.children.get(&cid) {
                        for cid in children {
                            if !visited.contains(cid) {
                                visit.push_back(*cid);
                            }
                        }
                    }
                }
                _ => {}
            }
        }
    }

    /// Demote a stochastic quantity to a free [`Parameter`](Node::Parameter), at the
    /// same [`Id`].
    ///
    /// The node keeps its identity and its quantity type, and every edge from a child into it is
    /// preserved, so a referencing tag `Q` stays valid and everything downstream is untouched.
    /// What it loses is its sampler, its parent edges, and its own log-density.
    ///
    /// This is how a quantity is re-rooted during marginalization. Demoting a node that is already
    /// a parameter is a no-op.
    ///
    /// **Returns the parents it severed.** Those nodes each just lost a child and may now be
    /// unreachable, which only a caller that tracks external handles can decide — so the ids
    /// are reported rather than acted on here. Dropping them on the floor is a leak that grows
    /// once per demotion, which is once per tick of a sliding window.
    ///
    /// Returns [`SkoroError::NodeNotFound`] if the node does not exist, or
    /// [`SkoroError::NotStochastic`] if it is neither stochastic nor already a parameter.
    pub fn demote_to_parameter(&mut self, id: Id) -> SkoroResult<Vec<Id>> {
        match self.nodes.get(&id) {
            Some(Node::Stochastic(_)) => {}
            // Already a free variable; nothing to demote.
            Some(Node::Parameter(_)) => return Ok(Vec::new()),
            Some(_) => return Err(SkoroError::NotStochastic { id }),
            None => return Err(SkoroError::NodeNotFound { id }),
        };
        // Checked before anything changes, so an error leaves the node stochastic and wired.
        let density = self.density_to_retire(id)?;
        let Some(Node::Stochastic(StochasticNode {
            id,
            parent_ids,
            quantity_type,
            ..
        })) = self.nodes.remove(&id)
        else {
            unreachable!("node kind validated above");
        };

        // Drop the edges from the old distribution's parameters into this node.
        self.unregister_children(id, &parent_ids);

        // A parameter has no marginal distribution, so it has no density either.
        self.nodes
            .insert(id, Node::Parameter(ParameterNode { id, quantity_type }));
        let mut orphaned = parent_ids;
        if let Some(dens_id) = density {
            self.retire_density(id, dens_id);
            orphaned.push(dens_id);
        }
        self.clear_cached_descendants(id);
        self.touch();
        Ok(orphaned)
    }

    /// Removes leaf nodes, verifying they have no children which would be kept in the graph.
    ///
    /// Returns an error if a node does not exist, or is still referenced as a parent of a node that
    /// is not also being removed.
    pub fn remove(&mut self, ids: &[Id]) -> SkoroResult<Vec<Node<B>>> {
        // Every id must exist before any of them is taken. Checked here rather than in the
        // removal loop below, where the `nodes.remove` miss used to surface: that left the
        // batch half-applied behind an error, and -- because `touch` is at the end -- half
        // applied without bumping the epoch, so a sequence compiled beforehand stayed live.
        for id in ids {
            if !self.nodes.contains_key(id) {
                return Err(SkoroError::NodeNotFound { id: *id });
            }
        }
        // Validate no dangling pointers.
        for id in ids {
            if let Some(children) = self.children.get(id)
                && let Some(child_id) = children.iter().find(|id| !ids.contains(id))
            {
                return Err(SkoroError::NodeStillReferenced {
                    id: *id,
                    child_id: *child_id,
                });
            }
        }
        for id in ids {
            if let Some(by) = self
                .bindings
                .referrers_of(*id)
                .find(|referrer| !ids.contains(referrer))
            {
                return Err(SkoroError::NodeStillBound { id: *id, by });
            }
        }
        // A stochastic node whose density survives the batch has that density retired below.
        // Check every such density now, while nothing has changed. What was checked holds through
        // the loop: the density lies outside the batch so no removal takes it, and the index is
        // one-to-one so no other removal retires it first.
        for id in ids {
            if let Some(Node::Stochastic(_)) = self.nodes.get(id)
                && let Some(dens_id) = self.stochastic_to_log_density.get(id)
                && !ids.contains(dens_id)
            {
                self.density_to_retire(*id)?;
            }
        }
        // Perform removal.
        let mut out = Vec::with_capacity(ids.len());
        for id in ids {
            // Not a parent-edge write: this drops the departing node's *own* children set,
            // which the loop above already proved is empty of survivors. Edges into this node
            // from its parents are `unregister_children`'s job, below.
            self.children.remove(id);
            let node = self
                .nodes
                .remove(id)
                .expect("existence checked before any removal");
            self.private_nodes.remove(id);
            self.bindings.remove_source(*id);
            self.bindings.remove_target(*id);
            let parent_ids = node.parent_ids().to_vec();
            self.unregister_children(*id, &parent_ids);
            match &node {
                &Node::Constant(_) | &Node::Observed(_) => {
                    self.pinnable.remove(id);
                }
                &Node::Stochastic(StochasticNode { id, .. }) => {
                    // A density need not be a *child* of the quantity it scores, so it can
                    // easily survive this removal. Retire it rather than merely forgetting the
                    // reverse index, or it is left claiming a node that no longer exists.
                    // A density inside this same batch is about to go anyway, and rewriting it
                    // first would change the node kind reported back to the caller.
                    match self.stochastic_to_log_density.get(&id).copied() {
                        Some(dens_id) if ids.contains(&dens_id) => {
                            self.stochastic_to_log_density.remove(&id);
                        }
                        Some(dens_id) => self.retire_density(id, dens_id),
                        None => {}
                    }
                }
                #[allow(clippy::collapsible_match)]
                &Node::LogLikelihood(LogLikelihoodNode { stochastic_id, .. }) => {
                    if let Some(stochastic_id) = stochastic_id {
                        self.stochastic_to_log_density.remove(&stochastic_id);
                    }
                    if let Some(index) = self.log_likelihoods.iter().position(|lid| *lid == *id) {
                        self.log_likelihoods.remove(index);
                    }
                }
                _ => {}
            };
            out.push(node);
        }
        self.touch();
        Ok(out)
    }

    /// Get the quantity type associated with a node by its Id.
    ///
    /// Returns [`SkoroError::NodeNotFound`] if the node does not exist, or
    /// [`SkoroError::QuantityTypeMismatch`] if the requested type does not match
    /// the type stored in the graph.
    pub fn get_quantity_type<K, T>(&self, id: Id) -> SkoroResult<T>
    where
        K: Kind<B>,
        T: QuantityType<B, K>,
    {
        self.get_quantity_type_impl(id)?
            .as_any()
            .downcast_ref::<T>()
            .cloned()
            .ok_or(SkoroError::QuantityTypeMismatch { id })
    }

    fn get_quantity_type_impl(&self, id: Id) -> SkoroResult<&dyn DynQuantityType<B>> {
        let node = self.nodes.get(&id).ok_or(SkoroError::NodeNotFound { id })?;
        match node {
            Node::Constant(ConstantNode { quantity_type, .. })
            | Node::Parameter(ParameterNode { quantity_type, .. })
            | Node::Mapped(MappedNode { quantity_type, .. })
            | Node::Stochastic(StochasticNode { quantity_type, .. })
            | Node::Observed(ObservedNode { quantity_type, .. })
            | Node::LogLikelihood(LogLikelihoodNode { quantity_type, .. }) => {
                Ok(quantity_type.as_ref())
            }
        }
    }

    /// The manifold structure of a continuous node, for tangent-space sizing.
    ///
    /// [`Node::LogDensity`] has no stored quantity type but is always real-valued, so it
    /// reports dimension 1 — which is what lets a layout name density nodes as rows.
    pub fn get_manifold(&self, id: Id) -> SkoroResult<&dyn skoro_riemann::DynManifold<B>> {
        self.get_quantity_type_impl(id)?
            .as_manifold()
            .ok_or(SkoroError::NotContinuous { id })
    }

    /// Check that every id may be a Jacobian column.
    ///
    /// A column is something an estimator moves, so a mapped or log-density node is
    /// [`SkoroError::MappedColumn`]: the passes collect derivatives only at leaves, and such a
    /// column would come back silently zero. Every leaf is accepted. A `Constant` or `Observed`
    /// column is a legitimate zero, and `observe` turns a stochastic column into an observed one
    /// at the same id, so a layout must not start failing because its state was observed.
    ///
    /// An id that is not a node is [`SkoroError::NodeNotFound`].
    pub fn ensure_leaf_columns(&self, ids: impl IntoIterator<Item = Id>) -> SkoroResult<()> {
        for id in ids {
            match self.node(id).ok_or(SkoroError::NodeNotFound { id })? {
                Node::Mapped(_) | Node::LogLikelihood(_) => {
                    return Err(SkoroError::MappedColumn { id });
                }
                Node::Parameter(_)
                | Node::Stochastic(_)
                | Node::Constant(_)
                | Node::Observed(_) => {}
            }
        }
        Ok(())
    }

    /// One [`Term`] per id in [`log_likelihoods`](Self::log_likelihoods), in that order.
    ///
    /// A term is [`in_density`](Term::in_density) as its node records, and
    /// [`in_proposal`](Term::in_proposal) when it scores a node that is currently
    /// [`Node::Stochastic`].
    pub fn terms(&self) -> Vec<Term> {
        self.log_likelihoods
            .iter()
            .map(|&density| {
                let scored = self.stochastic_of(density);
                let in_proposal = matches!(
                    scored.and_then(|s| self.nodes.get(&s)),
                    Some(Node::Stochastic(_))
                );
                Term {
                    density,
                    scored,
                    in_density: self.in_log_density(density),
                    in_proposal,
                }
            })
            .collect()
    }

    /// The sum of the named terms' log-densities at `points`.
    ///
    /// Every id must be in [`log_likelihoods`](Self::log_likelihoods) (else
    /// [`SkoroError::NotLogLikelihood`]), but nothing more is required of them: the caller
    /// chooses the set, and it need not be a subset of the model's log-density — this is how
    /// the proposal `q(x|z)` is summed. An empty slice yields zeros of shape `[batch, 1]`,
    /// batch taken from `points` exactly as [`log_density`](Self::log_density) does.
    pub fn log_density_terms(&self, points: &ValueMap<B>, terms: &[Id]) -> SkoroResult<Point<B>> {
        if let Some(id) = terms.iter().find(|id| !self.log_likelihoods.contains(id)) {
            return Err(SkoroError::NotLogLikelihood { id: *id });
        }
        self.sum_terms(points, terms)
    }

    /// The sum of `plus`'s log-densities less `minus`'s, in one compiled pass.
    ///
    /// `log_weight = Σ in_density − Σ in_proposal` is the caller this exists for. The two sets
    /// overlap almost entirely, and a term in both cancels to within rounding -- so summing
    /// them separately compiled a second program to walk most of the same graph and produce
    /// numbers that were about to be subtracted away. One program over the union costs one
    /// traversal, and the cancellation becomes exact rather than nearly exact.
    ///
    /// Every id on either side must be a likelihood term, else
    /// [`SkoroError::NotLogLikelihood`]. Two empty sides give zeros of shape `[batch, 1]`,
    /// batch taken from `points` exactly as [`log_density`](Self::log_density) does.
    pub fn log_density_terms_signed(
        &self,
        points: &ValueMap<B>,
        plus: &[Id],
        minus: &[Id],
    ) -> SkoroResult<Point<B>> {
        // One pass builds the union and validates, in the order the caller named things, so a
        // rejection reports the first offending id rather than an arbitrary one.
        let mut union: Vec<Id> = Vec::with_capacity(plus.len() + minus.len());
        for id in plus.iter().chain(minus) {
            if !self.log_likelihoods.contains(id) {
                return Err(SkoroError::NotLogLikelihood { id: *id });
            }
            if !union.contains(id) {
                union.push(*id);
            }
        }

        let compiled_sequence = self.compile_backward_from(&union)?;
        let batch_size = Self::batch_size_of(points);
        let forward_output = compiled_sequence.forward(ForwardInput {
            points,
            options: ForwardOptions {
                batch_size,
                use_model_samplers: false,
            },
        })?;

        let term_value = |id: &Id| {
            forward_output
                .evaluations
                .get(id)
                .expect("Log-likelihood should be evaluated.")
                .0
                .clone()
                .unwrap_float()
        };
        let mut total = Point::zeros([batch_size, 1], &Default::default());
        for id in plus {
            total = total + term_value(id);
        }
        for id in minus {
            total = total - term_value(id);
        }
        Ok(total)
    }

    /// [`log_density_terms_signed`](Self::log_density_terms_signed) with its gradient: the value
    /// `Σ plus − Σ minus` and its cotangent at every leaf, by one reverse pass.
    ///
    /// The program is the one the value-only form compiles, over the union of the two sides, so
    /// the two share a cache entry. Each target is seeded with its net sign, `+1` per appearance
    /// in `plus` and `−1` per appearance in `minus`, so a term on both sides is seeded with zero
    /// and cancels exactly in the gradient as in the value.
    ///
    /// At given points, as every evaluation here: a stochastic leaf is an independent variable,
    /// and no derivative flows through a sampler. The cotangent at a leaf is therefore the partial
    /// derivative of the signed sum with the leaf's value held as given, which is the
    /// score-function ingredient `∇_θ log q(x; θ)` at a fixed draw `x`, not a reparameterization
    /// gradient.
    ///
    /// Every id on either side must be a likelihood term, else [`SkoroError::NotLogLikelihood`].
    pub fn log_density_terms_signed_ord1(
        &self,
        points: &ValueMap<B>,
        plus: &[Id],
        minus: &[Id],
    ) -> SkoroResult<PointEvalOrder1<B>> {
        let mut union: Vec<Id> = Vec::with_capacity(plus.len() + minus.len());
        let mut sign: HashMap<Id, f64> = HashMap::new();
        for (id, s) in plus
            .iter()
            .map(|id| (id, 1.0))
            .chain(minus.iter().map(|id| (id, -1.0)))
        {
            if !self.log_likelihoods.contains(id) {
                return Err(SkoroError::NotLogLikelihood { id: *id });
            }
            if !union.contains(id) {
                union.push(*id);
            }
            *sign.entry(*id).or_insert(0.0) += s;
        }

        let compiled_sequence = self.compile_backward_from(&union)?;
        let batch_size = Self::batch_size_of(points);
        let cotangents: HashMap<Id, CotangentFrame<B>> = union
            .iter()
            .map(|id| {
                let seed = Tensor::ones([batch_size, 1, 1], &Default::default()) * sign[id];
                (*id, seed)
            })
            .collect();
        let vjp_output = compiled_sequence.vjp_forward(VjpForwardInput {
            points,
            cotangents: &cotangents,
            options: ForwardOptions {
                batch_size,
                use_model_samplers: false,
            },
        })?;

        let mut value = Point::zeros([batch_size, 1], &Default::default());
        for id in &union {
            let term = vjp_output
                .primal
                .evaluations
                .get(id)
                .expect("Log-likelihood should be evaluated.")
                .0
                .clone()
                .unwrap_float();
            value = value + term * sign[id];
        }
        let cotangents = vjp_output
            .cotangents
            .into_iter()
            .map(|(id, v)| (id, v.squeeze_dim(2)))
            .collect();
        Ok(PointEvalOrder1 { value, cotangents })
    }

    /// The batch axis the supplied points imply, defaulting to one when there are none.
    fn batch_size_of(points: &ValueMap<B>) -> usize {
        points
            .iter()
            .next()
            .map(|(_, point)| point.dims()[0])
            .unwrap_or(1)
    }

    /// How many compiled programs the cache is currently holding.
    ///
    /// Reads the cache's real state rather than counting compiles, which is enough to check
    /// that a caller compiles one program and not two. Behind `test-utils` because no
    /// production caller has a reason to look.
    #[cfg(feature = "test-utils")]
    pub fn cached_program_count(&self) -> usize {
        self.compiled
            .lock()
            .expect("compiled-sequence cache poisoned")
            .sequences
            .len()
    }

    /// Point the density index of `stochastic_id` at `density_id`, bypassing every check.
    ///
    /// For reaching the error paths that `validate_indices` makes unreachable, to show that a
    /// mutator hitting one leaves the graph unchanged. Neither validates nor bumps the epoch.
    #[cfg(feature = "test-utils")]
    pub fn corrupt_density_index(&mut self, stochastic_id: Id, density_id: Id) {
        self.stochastic_to_log_density
            .insert(stochastic_id, density_id);
    }

    /// Evaluate and sum `terms`, which the caller has checked are likelihood terms.
    fn sum_terms(&self, points: &ValueMap<B>, terms: &[Id]) -> SkoroResult<Point<B>> {
        let compiled_sequence = self.compile_backward_from(terms)?;
        let batch_size = Self::batch_size_of(points);
        let forward_output = compiled_sequence.forward(ForwardInput {
            points,
            options: ForwardOptions {
                batch_size,
                use_model_samplers: false,
            },
        })?;
        let mut log_density = Point::zeros([batch_size, 1], &Default::default());
        for log_likelihood_id in terms {
            log_density = log_density
                + forward_output
                    .evaluations
                    .get(log_likelihood_id)
                    .expect("Log-likelihood should be evaluated.")
                    .0
                    .clone()
                    .unwrap_float();
        }
        Ok(log_density)
    }

    /// Evaluate the log-density of the model at the specified values.
    ///
    /// Proposal-only terms are not summands of the model's log-density and are skipped; a model
    /// built entirely from proposals has a log-density of zero.
    pub fn log_density(&self, points: &ValueMap<B>) -> SkoroResult<Point<B>> {
        self.sum_terms(points, &self.density_term_ids())
    }

    /// The evaluation of [`log_density`](Self::log_density) with the first-order gradient
    /// calculation.
    pub fn log_density_ord1(&self, points: &ValueMap<B>) -> SkoroResult<PointEvalOrder1<B>> {
        let density_terms = self.density_term_ids();
        let compiled_sequence = self.compile_backward_from(&density_terms)?;
        let batch_size = if let Some((_, point)) = points.iter().next() {
            point.dims()[0]
        } else {
            1
        };

        let cotangents: HashMap<Id, CotangentFrame<B>> = density_terms
            .iter()
            .map(|id| (*id, Tensor::ones([batch_size, 1, 1], &Default::default())))
            .collect();

        let vjp_output = compiled_sequence.vjp_forward(VjpForwardInput {
            points,
            cotangents: &cotangents,
            options: ForwardOptions {
                batch_size,
                use_model_samplers: false,
            },
        })?;
        let mut log_density = Point::zeros([batch_size, 1], &Default::default());
        for log_likelihood_id in &density_terms {
            log_density = log_density
                + vjp_output
                    .primal
                    .evaluations
                    .get(log_likelihood_id)
                    .expect("Log-likelihood should be evaluated.")
                    .0
                    .clone()
                    .unwrap_float();
        }
        let cotangents = vjp_output
            .cotangents
            .into_iter()
            .map(|(id, v)| (id, v.squeeze_dim(2)))
            .collect();
        Ok(PointEvalOrder1 {
            value: log_density,
            cotangents,
        })
    }

    /// The evaluation of [`log_density`](Self::log_density) with the first-order gradient
    /// calculation and second-order Hessian-product calculation.
    pub fn log_density_ord2(
        &self,
        points: &ValueMap<B>,
        tangents: &HashMap<Id, TangentVector<B>>,
    ) -> SkoroResult<PointEvalOrder2<B>> {
        let density_terms = self.density_term_ids();
        let compiled_sequence = self.compile_backward_from(&density_terms)?;
        let batch_size = if let Some((_, point)) = points.iter().next() {
            point.dims()[0]
        } else {
            1
        };

        let ord1_cotangents: HashMap<Id, CotangentFrame<B>> = density_terms
            .iter()
            .map(|id| (*id, Tensor::ones([batch_size, 1, 1], &Default::default())))
            .collect();

        let ord2_cotangents: HashMap<Id, CotangentFrame<B>> = density_terms
            .iter()
            .map(|id| (*id, Tensor::zeros([batch_size, 1, 1], &Default::default())))
            .collect();

        let hvp_output = compiled_sequence.hvp_forward(HvpForwardInput {
            points,
            tangents,
            ord1_cotangents: &ord1_cotangents,
            ord2_cotangents: &ord2_cotangents,
            options: ForwardOptions {
                batch_size,
                use_model_samplers: false,
            },
        })?;
        let mut log_density = Point::zeros([batch_size, 1], &Default::default());
        for log_likelihood_id in &density_terms {
            log_density = log_density
                + hvp_output
                    .primal
                    .evaluations
                    .get(log_likelihood_id)
                    .expect("Log-likelihood should be evaluated.")
                    .0
                    .clone()
                    .unwrap_float();
        }
        let ord1_cotangents = hvp_output
            .ord1_cotangents
            .into_iter()
            .map(|(id, v)| (id, v.squeeze_dim(2)))
            .collect();
        let ord2_cotangents = hvp_output
            .ord2_cotangents
            .into_iter()
            .map(|(id, v)| (id, v.squeeze_dim(2)))
            .collect();
        Ok(PointEvalOrder2 {
            value: log_density,
            tangents: hvp_output.tangents,
            ord1_cotangents,
            ord2_cotangents,
        })
    }

